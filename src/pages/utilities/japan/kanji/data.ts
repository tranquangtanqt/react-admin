export const KANJI_LIST: KanjiDto[] = [...N5_KANJI];

export function getKanjiByCategory(categoryId: string): KanjiDto[] {
  return KANJI_LIST.filter((item) => item.categoryId === categoryId);
}

export function getCategoryItemCount(categoryId: string): number {
  if (categoryId === 'radicals') return RADICALS.length;
  return getKanjiByCategory(categoryId).length;
}

